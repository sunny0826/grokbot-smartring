#!/usr/bin/env python3
"""Generate the on-device UI subset from pinned, OFL-licensed Noto Sans CJK SC."""

import argparse
import hashlib
import pathlib
import re
import subprocess
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE_URL = (
    "https://raw.githubusercontent.com/notofonts/noto-cjk/"
    "523d033d6cb47f4a80c58a35753646f5c3608a78/"
    "Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf"
)
SOURCE_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"
CONVERTER = "lv_font_conv@1.5.3"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=pathlib.Path, help="Use a local copy of the pinned OTF")
    args = parser.parse_args()
    source = args.source.read_bytes() if args.source else urllib.request.urlopen(SOURCE_URL, timeout=60).read()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise SystemExit("Font SHA-256 mismatch; refusing to generate")

    # All Chinese characters in the UI, plus printable ASCII for timer/status text.
    ui_sources = [ROOT / "main/voice_ui.cpp", *sorted((ROOT / "main").glob("wifi_*.cpp"))]
    ui = "\n".join(path.read_text() for path in ui_sources)
    symbols = "".join(sorted(set(re.findall(r"[\u3000-\u9fff\uff00-\uffef]", ui))))
    output = ROOT / "main/fonts/voice_font_22.c"
    with tempfile.TemporaryDirectory(prefix="voice-font-") as directory:
        work = pathlib.Path(directory)
        (work / "source.otf").write_bytes(source)
        subprocess.run([
            "npm", "exec", "--yes", "--package=" + CONVERTER, "--", "lv_font_conv",
            "--font", "source.otf", "--size", "22", "--bpp", "4",
            "--range", "0x20-0x7e", "--symbols", symbols,
            "--format", "lvgl", "--no-compress", "--no-kerning",
            "--lv-font-name", "voice_font_22", "--lv-include", "lvgl.h",
            "-o", "voice_font_22.c",
        ], cwd=work, check=True)
        generated = (work / "voice_font_22.c").read_text()
    bitmap = re.search(r"(glyph_bitmap\[\] = \{\n)(.*?)(\n\};)", generated, re.S)
    if not bitmap:
        raise SystemExit("Missing generated bitmap")
    lines = bitmap.group(2).splitlines()
    includes = []
    for old in output.parent.glob("voice_font_bitmap_*.inc"):
        old.unlink()
    for index, start in enumerate(range(0, len(lines), 480)):
        name = f"voice_font_bitmap_{index:02d}.inc"
        (output.parent / name).write_text("\n".join(lines[start:start + 480]) + "\n")
        includes.append(f'#include "{name}"')
    generated = generated[:bitmap.start(2)] + "\n".join(includes) + generated[bitmap.end(2):]
    output.write_text(
        "/* GENERATED by tools/generate_voice_font.py; do not edit.\n"
        " * Noto Sans CJK SC subset; SIL OFL 1.1, see OFL.txt and README.md. */\n" + generated.rstrip() + "\n"
    )
    print(f"Generated {output}: {len(symbols)} CJK/punctuation glyphs + ASCII")


if __name__ == "__main__":
    main()
